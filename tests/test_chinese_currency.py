import pytest

from src.chinese_currency import amount_to_chinese_upper


@pytest.mark.parametrize(
    "amount, expected",
    [
        (100.00, "壹佰元整"),
        (1000.00, "壹仟元整"),
        (10000.00, "壹万元整"),
        # 万位节的低 4 位为零 —— 曾经多输出一个"万"（壹拾万万元整）
        (100000.00, "壹拾万元整"),
        (200000.00, "贰拾万元整"),
        (1000000.00, "壹佰万元整"),
        (10000000.00, "壹仟万元整"),
        (100000000.00, "壹亿元整"),
        # 同为 0 结尾但低 4 位有值 —— 不应受影响
        (110000.00, "壹拾壹万元整"),
        (101000.00, "壹拾万壹仟元整"),
        (100100.00, "壹拾万零壹佰元整"),
        (100010.00, "壹拾万零壹拾元整"),
        (100001.00, "壹拾万零壹元整"),
        (100200.00, "壹拾万零贰佰元整"),
        (1234567.00, "壹佰贰拾叁万肆仟伍佰陆拾柒元整"),
        (99999999.00, "玖仟玖佰玖拾玖万玖仟玖佰玖拾玖元整"),
        (100000000.50, "壹亿元伍角"),
        (200000.50, "贰拾万元伍角"),
        # 已有文档示例
        (154549.04, "壹拾伍万肆仟伍佰肆拾玖元零肆分"),
        (1257049.41, "壹佰贰拾伍万柒仟零肆拾玖元肆角壹分"),
        (10.05, "壹拾元零伍分"),
        (0.50, "零元伍角"),
    ],
)
def test_amount_to_chinese_upper(amount, expected):
    assert amount_to_chinese_upper(amount) == expected
